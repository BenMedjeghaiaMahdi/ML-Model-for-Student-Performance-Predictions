# Do clusters really exist? Hopkins statistic (about 0.5 = random data, close to 1 = clustered data).
def hopkins(data, repeats=50, seed=RANDOM_STATE):
    rng = np.random.RandomState(seed)
    data = np.asarray(data)
    n, d = data.shape
    m = max(1, int(0.1 * n))
    values = []

    for _ in range(repeats):
        sample = data[rng.choice(n, m, replace=False)]
        uniform_points = rng.uniform(data.min(axis=0), data.max(axis=0), size=(m, d))

        # u: distance from random points to the nearest real point
        u = np.sqrt(((uniform_points[:, None, :] - data[None, :, :]) ** 2).sum(axis=2)).min(axis=1)

        # w: distance from real points to the nearest OTHER real point
        dist = np.sqrt(((sample[:, None, :] - data[None, :, :]) ** 2).sum(axis=2))
        dist[dist == 0] = np.inf
        w = dist.min(axis=1)

        values.append(u.sum() / (u.sum() + w.sum()))

    return np.mean(values)

