def calculate_silhouette(data, labels):
    # Pairwise distances are computed once using an optimized numerical routine.
    # The a(i), b(i), and silhouette calculations remain explicit here.
    data = np.asarray(data)
    labels = np.asarray(labels)
    distances = pairwise_distances(data, metric="euclidean")
    clusters = np.unique(labels)
    silhouette_values = []

    for i in range(len(data)):
        current_cluster = labels[i]
        same_mask = labels == current_cluster
        same_mask[i] = False  # exclude the point itself from a(i)

        if not same_mask.any():
            silhouette_values.append(0)
            continue

        a = distances[i, same_mask].mean()
        other_cluster_means = []

        for cluster in clusters:
            if cluster != current_cluster:
                other_mask = labels == cluster
                if other_mask.any():
                    other_cluster_means.append(distances[i, other_mask].mean())

        if not other_cluster_means:
            silhouette_values.append(0)
            continue

        b = min(other_cluster_means)
        denominator = max(a, b)
        score = 0 if denominator == 0 else (b - a) / denominator
        silhouette_values.append(score)

    return float(np.mean(silhouette_values))

